using System.Text;
using MathForge.SourceGenerators.Vectors.Entities;
using Microsoft.CodeAnalysis;
using Microsoft.CodeAnalysis.Text;

namespace MathForge.SourceGenerators.Vectors;

internal static class VectorSourceBuilder
{
	public static void AddSource(
		SourceProductionContext context,
		VectorModel model,
		string suffix,
		string members)
	{
		if (string.IsNullOrWhiteSpace(members))
			return;

		var ns = model.Symbol.ContainingNamespace;

		var namespaceDeclaration = ns.IsGlobalNamespace
			? string.Empty
			: $"namespace {ns.ToDisplayString()};";

		var source = $$"""
		               // <auto-generated/>
		               #nullable enable

		               {{namespaceDeclaration}}

		               public readonly partial record struct {{model.Symbol.Name}}
		               {
		               {{members}}
		               }
		               """;

		var hintName = $"{SymbolHint(model.Symbol)}.{suffix}.g.cs";

		context.AddSource(
			hintName,
			SourceText.From(source, Encoding.UTF8));
	}

	private static string SymbolHint(INamedTypeSymbol symbol)
	{
		var fullName = symbol.ToDisplayString(
			SymbolDisplayFormat.FullyQualifiedFormat);

		return string.Concat(
			fullName.Select(static c =>
				char.IsLetterOrDigit(c) ? c : '_'));
	}
}